import assert from 'node:assert/strict';
import fs from 'node:fs';
import {resolveIdentity} from './identity-policy.mjs';
import {calcularDescartesPiloto,calcularRankingComDescarte} from '../src/utils/descarte.js';
const source=fs.readFileSync('src/utils/rankingCalc.js','utf8').replace(/import .*?;\r?\n/,'');
const {computarPontos}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const owner='owner@example.com',user='driver@gmail.com';
const payload={email:user,email_verified:true,sub:'driver'};
assert.equal(resolveIdentity('google',payload,{email:owner}),user,'old admin binding must not win');
assert.equal(resolveIdentity('google',payload,null),user);
assert.throws(()=>resolveIdentity('google',{...payload,email_verified:false},null));
assert.throws(()=>resolveIdentity('google',{...payload,email:'driver@untrusted.com'},null));
assert.throws(()=>resolveIdentity('microsoft',payload,null));
const r={piloto_nome:'A',etapa_id:'1',posicao:1,pontos:999,pontos_melhor_volta:2,tipos_ponto_aplicados:[{valor:3}]};
assert.equal(computarPontos(r,{dobrar_pontos:true},{1:{pontos:25}},{'A||1':4}).pontos_totais,51);
assert.equal(computarPontos({...r,status:'DQ'},{},{1:{pontos:25}},{}).pontos_totais,0);
assert.equal(computarPontos({...r,status:'NC'},{},{1:{pontos:25}},{}).pontos_totais,0);
assert.equal(computarPontos({...r,pontos_melhor_volta:0,tipos_ponto_aplicados:[]},{},{},{}).pontos_totais,0);
const rows=[{piloto_nome:'A',etapa_id:'1',pontos_totais:10,pontos_penalidade:1},{piloto_nome:'A',etapa_id:'2',pontos_totais:20}];
assert.deepEqual(calcularDescartesPiloto(rows,2,0,1).etapasDescartadas,['2']);
assert.equal(calcularDescartesPiloto(rows,3,0,1).etapasDescartadas.length,0);
assert.equal(calcularDescartesPiloto(rows,4,0,1).descartesAutomaticos,1);
const rank=calcularRankingComDescarte({resultados:[{piloto_nome:'A',etapa_id:'1',pontos_totais:25}],etapas:[],campeonato:{descarte_quantidade:1}});
assert.equal(rank.length,1,'a pilot must remain visible even if all results were discarded');
assert.equal(rank[0].pontos_totais,0);assert.equal(rank[0].etapas_disputadas,1);
console.log('OK: identity isolation, verified emails, double points, bonuses, penalties, NC/DQ, missing score, absences and discarded pilot visibility.');
